#!/usr/bin/env python3
"""Regenerates api/_imgdata.js from the site's photography.
Why: the GitHub write path for this repo is text-only, so photo bytes are
stored as base64 string chunks (array-join format) and decoded at runtime
by api/img.js — the same pattern the flagship uses for embedded images.

Image sources (2026-11-24 image replacement, Ramone's directive):
  hero-tech + the nine svc-* photos are copied from the flagship
  topspeedserviceos.com library (apps/web photo-*.jpg + apps/web/service/
  hero-tech.webp), processed to WebP in
  ~/workspace/repairs-image-replacement/processed/.
  city-van is the premium package's art-directed van photo.
After regenerating, verify: node -e "const D=require('./api/_imgdata');
for (const k in D){const b=Buffer.from(D[k].b64,'base64');
const c=require('crypto');console.log(k,b.length,
c.createHash('md5').update(b).digest('hex')===D[k].md5?'MATCH':'MISMATCH')}"
"""
import base64, hashlib, os

PROC = os.path.expanduser("~/workspace/repairs-image-replacement/processed")
SRC = {
    "hero-tech": f"{PROC}/hero-tech.webp",
    "city-van": os.path.expanduser("~/workspace/premium-redesign-figma/assets/media-generation-ts-city-van-street-0-5e5d3bc4-4f4e-43ef-8131-b8479686a7a4.webp"),
    "svc-refrigerator": f"{PROC}/svc-refrigerator.webp",
    "svc-washer": f"{PROC}/svc-washer.webp",
    "svc-dryer": f"{PROC}/svc-dryer.webp",
    "svc-oven": f"{PROC}/svc-oven.webp",
    "svc-dishwasher": f"{PROC}/svc-dishwasher.webp",
    "svc-freezer": f"{PROC}/svc-freezer.webp",
    "svc-microwave": f"{PROC}/svc-microwave.webp",
    "svc-disposal": f"{PROC}/svc-disposal.webp",
    "svc-installation": f"{PROC}/svc-installation.webp",
}

def main():
    out = ["/* GENERATED by gen_imgdata.py — base64 chunks (array-join) of the",
           "   site's photography (flagship + premium package sources). Do not edit. */",
           "module.exports = {"]
    for name, path in SRC.items():
        raw = open(path, "rb").read()
        b64 = base64.b64encode(raw).decode()
        chunks = [b64[i:i+4000] for i in range(0, len(b64), 4000)]
        out.append(f"  {name!r}: {{ type: 'image/webp', md5: '{hashlib.md5(raw).hexdigest()}', b64: [")
        out += [f"    '{c}'," for c in chunks]
        out.append("  ].join('') },")
        print(name, len(raw), "bytes")
    out.append("};")
    open(os.path.join(os.path.dirname(os.path.abspath(__file__)), "api", "_imgdata.js"), "w").write("\n".join(out) + "\n")

if __name__ == "__main__":
    main()
